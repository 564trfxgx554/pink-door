-- Pink Door schema (PostgreSQL).
-- Spring sql.init runs this on every startup (mode: always), so every
-- statement must be safe to run twice: CREATE TABLE / INDEX IF NOT EXISTS,
-- CREATE OR REPLACE FUNCTION, DROP TRIGGER IF EXISTS.

CREATE TABLE IF NOT EXISTS pd_user (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname   VARCHAR(64)  NOT NULL,
    password   VARCHAR(100) NOT NULL,
    avatar     VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_pd_user_nickname UNIQUE (nickname)
);
COMMENT ON TABLE pd_user IS 'Pink Door 用户表';
COMMENT ON COLUMN pd_user.nickname IS '登录昵称';
COMMENT ON COLUMN pd_user.password IS 'BCrypt 密码哈希';
COMMENT ON COLUMN pd_user.avatar IS '头像地址';
COMMENT ON COLUMN pd_user.created_at IS '创建时间';
COMMENT ON COLUMN pd_user.updated_at IS '更新时间';

CREATE TABLE IF NOT EXISTS pd_ai_conversation (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL,
    title           VARCHAR(100) NOT NULL DEFAULT '新的聊天',
    last_message_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE pd_ai_conversation IS 'Pink Door AI 会话';
COMMENT ON COLUMN pd_ai_conversation.user_id IS '所属用户';
COMMENT ON COLUMN pd_ai_conversation.title IS '会话标题';
COMMENT ON COLUMN pd_ai_conversation.last_message_at IS '最后消息时间';
COMMENT ON COLUMN pd_ai_conversation.created_at IS '创建时间';
COMMENT ON COLUMN pd_ai_conversation.updated_at IS '更新时间';

CREATE TABLE IF NOT EXISTS pd_ai_message (
    id              BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL,
    role            VARCHAR(16) NOT NULL,
    content         TEXT      NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE pd_ai_message IS 'Pink Door AI 聊天消息';
COMMENT ON COLUMN pd_ai_message.conversation_id IS '会话 ID';
COMMENT ON COLUMN pd_ai_message.role IS '角色：user / assistant';
COMMENT ON COLUMN pd_ai_message.content IS '消息内容';
COMMENT ON COLUMN pd_ai_message.created_at IS '创建时间';

CREATE INDEX IF NOT EXISTS idx_pd_ai_conversation_user
    ON pd_ai_conversation (user_id, last_message_at);
CREATE INDEX IF NOT EXISTS idx_pd_ai_message_conversation
    ON pd_ai_message (conversation_id, id);

-- NOTE: PostgreSQL has no ON UPDATE for columns. The updated_at trigger
-- used to live here, but Spring Boot's SQL script runner splits scripts on
-- semicolons and cannot parse a $$-quoted PL/pgSQL function body, which
-- crashed the app at startup. So there is intentionally no trigger: the
-- app never writes updated_at itself (FieldStrategy.NEVER) and orders
-- conversations by last_message_at, which the app updates explicitly.

-- ========== 多租户：情侣空间 ==========
-- 一行代表一对情侣，是多租户的边界。云上已有的 pd_user / pd_ai_conversation
-- 表通过下面的 ADD COLUMN IF NOT EXISTS 补列，重复启动安全。

CREATE TABLE IF NOT EXISTS pd_couple (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(64) NOT NULL DEFAULT '我们的小屋',
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE pd_couple IS 'Pink Door 情侣空间';
COMMENT ON COLUMN pd_couple.name IS '空间名称';

ALTER TABLE pd_user ADD COLUMN IF NOT EXISTS couple_id BIGINT;
ALTER TABLE pd_ai_conversation ADD COLUMN IF NOT EXISTS couple_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_pd_user_couple
    ON pd_user (couple_id);
CREATE INDEX IF NOT EXISTS idx_pd_ai_conversation_couple_user
    ON pd_ai_conversation (couple_id, user_id, last_message_at);

-- NOTE: 云上已有的用户行和会话行，couple_id 初始为 NULL。启动时
-- PresetAccountInitializer 会按 preset-accounts 把两个账号绑到空间上；
-- 旧的 pd_ai_conversation 行需要另外手动回填一次（见部署说明），否则
-- 租户插件会把它们过滤掉：
--   UPDATE pd_ai_conversation c SET couple_id = u.couple_id
--     FROM pd_user u WHERE c.user_id = u.id AND c.couple_id IS NULL;

-- ========== 默契问答 ==========

-- 房间：一局游戏一条记录，只属于一个情侣空间。
CREATE TABLE IF NOT EXISTS pd_quiz_room (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    couple_id     BIGINT      NOT NULL,
    status        VARCHAR(16) NOT NULL DEFAULT 'waiting',
    current_round INT         NOT NULL DEFAULT 0,
    total_rounds  INT         NOT NULL DEFAULT 5,
    created_by    BIGINT      NOT NULL,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at   TIMESTAMP   DEFAULT NULL
);
COMMENT ON TABLE pd_quiz_room IS 'Pink Door 默契问答房间';
COMMENT ON COLUMN pd_quiz_room.status IS 'waiting / playing / finished';
COMMENT ON COLUMN pd_quiz_room.current_round IS '当前题号';
COMMENT ON COLUMN pd_quiz_room.total_rounds IS '总题数';
COMMENT ON COLUMN pd_quiz_room.created_by IS '创建人';
COMMENT ON COLUMN pd_quiz_room.finished_at IS '结束时间';

CREATE INDEX IF NOT EXISTS idx_quiz_room_couple
    ON pd_quiz_room (couple_id, status, created_at);

-- 题库：全局共享，不按情侣隔离，租户插件忽略这张表。
CREATE TABLE IF NOT EXISTS pd_quiz_question (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content    VARCHAR(255) NOT NULL,
    options    TEXT         NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE pd_quiz_question IS 'Pink Door 默契问答题库';
COMMENT ON COLUMN pd_quiz_question.options IS 'JSON 数组，例如 ["火锅","奶茶","蛋糕","烧烤"]';

-- 每一轮：房间 + 题号 + 题目。
CREATE TABLE IF NOT EXISTS pd_quiz_round (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    couple_id    BIGINT      NOT NULL,
    room_id      BIGINT      NOT NULL,
    round_no     INT         NOT NULL,
    question_id  BIGINT      NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'answering',
    started_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deadline_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_quiz_round UNIQUE (room_id, round_no)
);
COMMENT ON TABLE pd_quiz_round IS 'Pink Door 默契问答轮次';
COMMENT ON COLUMN pd_quiz_round.round_no IS '第几题，从 1 开始';
COMMENT ON COLUMN pd_quiz_round.status IS 'answering / revealed';

CREATE INDEX IF NOT EXISTS idx_quiz_round_couple
    ON pd_quiz_round (couple_id, room_id);

-- 答案：一人一题一行，唯一键防重复提交。
CREATE TABLE IF NOT EXISTS pd_quiz_answer (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    couple_id    BIGINT      NOT NULL,
    room_id      BIGINT      NOT NULL,
    round_no     INT         NOT NULL,
    user_id      BIGINT      NOT NULL,
    option_index INT         NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_quiz_answer UNIQUE (room_id, round_no, user_id)
);
COMMENT ON TABLE pd_quiz_answer IS 'Pink Door 默契问答答案';
COMMENT ON COLUMN pd_quiz_answer.user_id IS '答题人';
COMMENT ON COLUMN pd_quiz_answer.option_index IS '选项下标，从 0 开始';

CREATE INDEX IF NOT EXISTS idx_quiz_answer_couple
    ON pd_quiz_answer (couple_id, room_id, round_no);
